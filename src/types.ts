import type { ComponentType } from 'react'
import type { Lang } from './i18n'

/**
 * Тексты одного демо на одном языке. Индексная сигнатура нужна, чтобы демо могли
 * держать здесь же свои подписи к кнопкам и панелям — внутри файла демо они
 * типизируются точно, потому что берутся из локального объекта, а не отсюда.
 */
export type DemoText = {
  /** Одна строка: зачем нужен хук. */
  tagline: string
  /** Минимальный пример — то, что слева. */
  code: string
  /** Нюансы, ради которых обычно и лезут в доку. Поддерживает `code` в бэктиках. */
  notes: string[]
  [key: string]: unknown
}

export type HookDemo = {
  /** Имя хука, оно же id секции и якорь в url. */
  id: string
  /** Пакет, из которого хук импортируется. */
  pkg: 'react' | 'react-dom'
  /** Живая визуализация — то, что справа. */
  Demo: ComponentType
  /** Тексты демо по языкам. */
  text: Record<Lang, DemoText>
  /** Версия React, начиная с которой хук доступен. */
  since?: string
}
